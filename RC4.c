#include <stdio.h>    // Includes standard input/output library for printing to the console.
#include <stdint.h>   // Includes standard integer types to ensure consistent sizing (e.g., uint64_t).
#include <intrin.h>   // Includes intrinsic functions for Windows, specifically for __rdtsc().

#define SWAP(a, b) do { unsigned char t = (a); (a) = (b); (b) = t; } while(0) // Macro to swap two bytes inline without function call overhead.
#define KEY_LENGTH 16 // Defines the static key length of 16 bytes as requested by the assignment parameters.
#define OUT_LENGTH 1024 // Defines the number of PRGA output bytes to generate for stable cycle measurement.

void KSA(unsigned char *S, const unsigned char *key) { // Defines the Key Scheduling Algorithm function taking the state array and key.
    int i; // Declares loop counter 'i' as an integer.
    unsigned char j = 0; // Declares and initializes 'j' as an unsigned char (8-bit) to guarantee zero-cost modulo 256 arithmetic.
    
    for (i = 0; i < 256; i++) { // Loops 256 times to initialize the identity permutation of the S-box.
        S[i] = (unsigned char)i; // Casts the loop counter 'i' to an unsigned char and assigns it to S[i].
    } // Ends the initialization loop.
    
    for (i = 0; i < 256; i++) { // Loops 256 times to scramble the S-box based on the cryptographic key.
        j = (unsigned char)(j + S[i] + key[i & 15]); // Calculates new 'j' index using bitwise AND (& 15) as a faster alternative to modulo 16. Natural 8-bit overflow handles modulo 256.
        SWAP(S[i], S[j]); // Swaps the values at S[i] and S[j] using the inline macro to mutate the state.
    } // Ends the permutation loop.
} // Ends the KSA function.

void PRGA(unsigned char *S, unsigned char *out, int len) { // Defines the Pseudo-Random Generation Algorithm to produce the keystream.
    int t; // Declares the loop counter 't' for the requested output length.
    unsigned char i = 0; // Initializes index 'i' to 0 as an 8-bit unsigned integer.
    unsigned char j = 0; // Initializes index 'j' to 0 as an 8-bit unsigned integer.
    
    for (t = 0; t < len; t++) { // Loops 'len' times to generate the requested number of keystream bytes.
        i = (unsigned char)(i + 1); // Increments 'i' by 1; wraps around to 0 automatically if it reaches 256.
        j = (unsigned char)(j + S[i]); // Adds the value of S[i] to 'j', naturally wrapping around modulo 256.
        SWAP(S[i], S[j]); // Swaps S[i] and S[j] to continuously mutate the internal state array.
        out[t] = S[(unsigned char)(S[i] + S[j])]; // Computes the sum of S[i] and S[j], uses it as an index, and stores the resulting byte in the output array.
    } // Ends the keystream generation loop.
} // Ends the PRGA function.

int main() { // Main execution entry point for the C program.
    unsigned char S[256]; // Allocates 256 bytes on the stack for the RC4 state array (S-box).
    unsigned char key[KEY_LENGTH] = {0x01, 0x23, 0x45, 0x67, 0x89, 0xAB, 0xCD, 0xEF, 0x10, 0x32, 0x54, 0x76, 0x98, 0xBA, 0xDC, 0xFE}; // Initializes a dummy 16-byte cryptographic key.
    unsigned char keystream[OUT_LENGTH]; // Allocates a buffer to hold the output keystream generated by the PRGA.
    
    uint64_t start_tsc, end_tsc; // Declares 64-bit unsigned integers to store the CPU time-stamp counter before and after execution.
    uint64_t ksa_cycles, prga_total_cycles; // Declares 64-bit variables to hold the calculated cycle differences.
    double cycles_per_byte; // Declares a double-precision floating-point variable to store the fractional PRGA cycles per byte.
    
    start_tsc = __rdtsc(); // Reads the CPU's time-stamp counter immediately prior to starting the KSA.
    KSA(S, key); // Calls the Key Scheduling Algorithm to initialize and scramble the S-box based on the key.
    end_tsc = __rdtsc(); // Reads the CPU's time-stamp counter immediately after the KSA completes.
    ksa_cycles = end_tsc - start_tsc; // Subtracts the start time from the end time to determine total clock cycles consumed by the KSA.
    
    start_tsc = __rdtsc(); // Reads the CPU's time-stamp counter immediately prior to starting the PRGA.
    PRGA(S, keystream, OUT_LENGTH); // Calls the Pseudo-Random Generation Algorithm to generate 1024 keystream bytes.
    end_tsc = __rdtsc(); // Reads the CPU's time-stamp counter immediately after the PRGA completes.
    
    prga_total_cycles = end_tsc - start_tsc; // Calculates the total cycles consumed by the PRGA for the entire output buffer.
    cycles_per_byte = (double)prga_total_cycles / OUT_LENGTH; // Divides the total PRGA cycles by the number of output bytes to find the average per byte.
    
    printf("--- RC4 Implementation Measurements ---\n"); // Prints a header for the output data.
    printf("1. KSA Total Clock Cycles: %llu\n", ksa_cycles); // Outputs the absolute number of CPU clock cycles taken by the KSA algorithm.
    printf("2. PRGA Cycles per Output Byte: %.2f\n", cycles_per_byte); // Outputs the amortized CPU clock cycles required to generate one keystream byte.
    
    return 0; // Returns 0 to the operating system, indicating successful program termination.
} // Ends the main function.
